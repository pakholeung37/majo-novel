#nullable enable
using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace Majo.CommandGenerator;

public static class CommandEmitter
{
    private const string P = "global::Majo.Runtime.Dialogue.Commands.";
    private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, true);
    private static string Number(double value) => value.ToString("R", CultureInfo.InvariantCulture) + "D";
    private static string Factory(ParameterModel parameter) => parameter.HasParameterlessConverter
        ? $"static () => new {parameter.ConverterTypeFullName}()" : "null";

    public static string Emit(CommandModel model)
    {
        var text = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
        if (model.ContainingNamespace.Length != 0) text.AppendLine($"namespace {model.ContainingNamespace};");
        text.AppendLine($"partial class {model.ClassName}\n{{");
        text.AppendLine($"    private static readonly {P}CommandDefinition<{model.ArgumentsFullTypeName}> StaticDefinition =");
        text.AppendLine($"        {P}CommandDefinition<{model.ArgumentsFullTypeName}>.Create({Literal(model.Name)}, category: {(model.Category is null ? "null" : Literal(model.Category))})");
        foreach (var member in model.Members)
        {
            if (member is ParameterModel p)
            {
                var method = p.IsPrimary ? "Primary" : p.IsRequired ? "Required" : "Optional";
                text.Append($"        .{method}<{p.ValueTypeFullName}>({Literal(p.Name)}, memberName: {Literal(p.MemberName)}, valueHint: {Literal(p.ValueHint)}, order: {p.Order}");
                if (p.DefaultText is not null) text.Append($", defaultText: {Literal(p.DefaultText)}");
                if (p.Minimum.HasValue) text.Append($", minimum: {Number(p.Minimum.Value)}");
                if (p.ConverterTypeFullName is not null) text.Append($", converter: typeof({p.ConverterTypeFullName}), converterFactory: {Factory(p)}");
                text.AppendLine(")");
            }
            else if (member is GroupModel group) text.AppendLine($"        .Group({Group(group)})");
        }
        foreach (var set in model.ParameterSets)
            text.AppendLine($"        .ParameterSet({P}CommandParameterSetRule.{set.RuleName}, {string.Join(", ", set.ParameterNames.Select(Literal))})");
        text.AppendLine("        .Build(static context =>\n        {");
        var slots = new Dictionary<string, string>();
        void Resolve(IReadOnlyList<ArgumentMemberModel> members, string prefix)
        {
            foreach (var member in members)
            {
                var path = prefix + member.MemberName;
                if (member is GroupModel group) Resolve(group.Members, path + ".");
                else
                {
                    var slot = "slot_" + Sanitize(path + member.MemberName);
                    slots.Add(path, slot);
                    text.AppendLine($"            var {slot} = context.GetMemberSlot({Literal(path)});");
                }
            }
        }
        Resolve(model.Members, "");
        string Construct(string type, IReadOnlyList<ArgumentMemberModel> members, string prefix) =>
            $"new {type}({string.Join(", ", members.Select(member => member is GroupModel g
                ? Construct(g.GroupTypeFullName, g.Members, prefix + g.MemberName + ".")
                : $"reader.{(((ParameterModel)member).IsRequired ? "ReadRequired" : "ReadOptional")}<{((ParameterModel)member).ValueTypeFullName}>({slots[prefix + member.MemberName]})"))})";
        text.AppendLine($"            return reader => {Construct(model.ArgumentsFullTypeName, model.Members, "")};\n        }});");
        text.AppendLine($"    public override {P}CommandDefinition<{model.ArgumentsFullTypeName}> Definition => StaticDefinition;\n}}");
        return text.ToString();
    }

    private static string Parameter(ParameterModel p) =>
        $"new {P}CommandParameterDeclaration(Name: {Literal(p.Name)}, MemberName: {Literal(p.MemberName)}, Order: {p.Order}, Primary: {Bool(p.IsPrimary)}, Required: {Bool(p.IsRequired)}, ValueType: typeof({p.ValueTypeFullName}), IsCommandValue: {Bool(p.IsCommandValue)}, ValueHint: {Literal(p.ValueHint)}, HasDefault: {Bool(p.HasDefault)}, DefaultText: {(p.DefaultText is null ? "null" : Literal(p.DefaultText))}, Minimum: {(p.Minimum.HasValue ? Number(p.Minimum.Value) : "null")}, ConverterType: {(p.ConverterTypeFullName is null ? "null" : $"typeof({p.ConverterTypeFullName})")}, ConverterFactory: {Factory(p)})";
    private static string Bool(bool value) => value ? "true" : "false";
    private static string Sanitize(string value) => new(value.Select(c => char.IsLetterOrDigit(c) ? c : '_').ToArray());
    private static string Group(GroupModel group) =>
        $"new {P}CommandGroupDeclaration(Name: {Literal(group.Name)}, MemberName: {Literal(group.MemberName)}, Order: {group.Order}, GroupType: typeof({group.GroupTypeFullName}), ConfigurationFactory: {(group.ConfigurationTypeFullName is null ? "null" : $"static () => new {group.ConfigurationTypeFullName}()")}, Parameters: new {P}CommandParameterDeclaration[] {{ {string.Join(", ", group.Parameters.Select(Parameter))} }}, SubGroups: new {P}CommandGroupDeclaration[] {{ {string.Join(", ", group.SubGroups.Select(Group))} }}, ParameterSets: new {P}CommandParameterSetSpec[] {{ {string.Join(", ", group.ParameterSets.Select(s => $"new {P}CommandParameterSetSpec({P}CommandParameterSetRule.{s.RuleName}, new string[] {{ {string.Join(", ", s.ParameterNames.Select(Literal))} }})"))} }})";
}
